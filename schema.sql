-- Authentication & Core Users
CREATE TABLE institutions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    description TEXT,
    address     VARCHAR(500),
    phone       VARCHAR(50),
    email       VARCHAR(255),
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(100) UNIQUE NOT NULL,
    email               VARCHAR(255) UNIQUE NOT NULL,
    full_name           VARCHAR(255),
    role                VARCHAR(50) NOT NULL 
        CHECK (role IN ('tutor', 'student', 'admin', 'college', 'institution', 'representative')),
    password_hash       VARCHAR(255) NOT NULL,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at   TIMESTAMP,
    last_login_at       TIMESTAMP,
    student_code        VARCHAR(50),                -- students only
    tutor_code          VARCHAR(50),                -- tutors only
    institution_id      BIGINT,                     -- tutors only
    data                JSONB,                      -- tutors only (flexible metadata)
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_users_institution 
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE SET NULL
);

CREATE TABLE institution_contacts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id  BIGINT NOT NULL,
    name            VARCHAR(255) NOT NULL,
    email           VARCHAR(255),
    phone           VARCHAR(50),
    is_primary      BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_contacts_institution 
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    token       VARCHAR(255) UNIQUE NOT NULL,
    expires_at  TIMESTAMP NOT NULL,
    is_used     BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_reset_user 
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE user_sessions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    session_token   VARCHAR(255) UNIQUE NOT NULL,
    expires_at      TIMESTAMP NOT NULL,
    ip_address      VARCHAR(45),
    user_agent      TEXT,
    last_accessed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_session_user 
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- Course & Batch Structure
CREATE TABLE courses (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    description     TEXT,
    instructor_id   BIGINT,
    institution_id  BIGINT NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_course_instructor 
        FOREIGN KEY (instructor_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_course_institution 
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

CREATE TABLE batches (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    start_date      DATE,
    end_date        DATE,
    allocation_time VARCHAR(100),               -- e.g. '10:00 AM - 12:00 PM'
    course_id       INT NOT NULL,
    tutor_id        BIGINT,
    institution_id  BIGINT NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'completed')),
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_batch_course 
        FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_batch_tutor 
        FOREIGN KEY (tutor_id) REFERENCES users(id) ON DELETE SET NULL,
    CONSTRAINT fk_batch_institution 
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

CREATE TABLE enrollments (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT NOT NULL,
    batch_id        INT NOT NULL,
    enrollment_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status          VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'completed')),

    CONSTRAINT fk_enrollment_student 
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollment_batch 
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT uq_enrollment UNIQUE (student_id, batch_id)
);

CREATE TABLE modules (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   INT NOT NULL,
    name        VARCHAR(255) NOT NULL,
    order_num   INT NOT NULL,
    is_locked   BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_module_course 
        FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);

CREATE TABLE topics (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id   INT NOT NULL,
    name        VARCHAR(255) NOT NULL,
    order_num   INT NOT NULL,

    CONSTRAINT fk_topic_module 
        FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE CASCADE
);

CREATE TABLE lessons (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id    INT NOT NULL,
    name        VARCHAR(255) NOT NULL,
    content_text TEXT,
    image_url   VARCHAR(500),
    video_url   VARCHAR(500),
    order_num   INT NOT NULL,

    CONSTRAINT fk_lesson_topic 
        FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE CASCADE
);

-- Assessments
CREATE TABLE quizzes (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id    INT NOT NULL,
    name        VARCHAR(255) NOT NULL,
    instructions TEXT,

    CONSTRAINT fk_quiz_topic 
        FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE CASCADE
);

CREATE TABLE quiz_questions (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id         INT NOT NULL,
    question_text   TEXT NOT NULL,
    options         JSONB,                      -- array of choices
    correct_answer  VARCHAR(500),
    type            VARCHAR(20) NOT NULL 
        CHECK (type IN ('mcq', 'short')),

    CONSTRAINT fk_question_quiz 
        FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
);

CREATE TABLE assignments (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id   INT NOT NULL,
    name        VARCHAR(255) NOT NULL,
    instructions TEXT,
    due_date    DATE,
    max_score   DECIMAL(5,2),
    status      VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'completed')),

    CONSTRAINT fk_assignment_module 
        FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE CASCADE
);

CREATE TABLE assignment_criteria (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id   INT NOT NULL,
    criteria_name   VARCHAR(255) NOT NULL,
    max_points      DECIMAL(5,2) NOT NULL,

    CONSTRAINT fk_criteria_assignment 
        FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE
);

-- Submissions & Progress
CREATE TABLE quiz_submissions (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT NOT NULL,
    quiz_id         INT NOT NULL,
    enrollment_id   INT NOT NULL,
    submission_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    score           DECIMAL(5,2),
    status          VARCHAR(30) NOT NULL DEFAULT 'pending_review'
        CHECK (status IN ('pending_review', 'reviewed', 'completed')),

    CONSTRAINT fk_submission_student 
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_submission_quiz 
        FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE,
    CONSTRAINT fk_submission_enrollment 
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE
);

CREATE TABLE quiz_answers (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id   INT NOT NULL,
    question_id     INT NOT NULL,
    selected_answer TEXT,
    is_correct      BOOLEAN,

    CONSTRAINT fk_answer_submission 
        FOREIGN KEY (submission_id) REFERENCES quiz_submissions(id) ON DELETE CASCADE,
    CONSTRAINT fk_answer_question 
        FOREIGN KEY (question_id) REFERENCES quiz_questions(id) ON DELETE CASCADE
);

CREATE TABLE assignment_submissions (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT NOT NULL,
    assignment_id   INT NOT NULL,
    enrollment_id   INT NOT NULL,
    submission_date TIMESTAMP,
    file_url        VARCHAR(500),
    grade           DECIMAL(5,2),
    feedback        TEXT,
    status          VARCHAR(30) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'submitted', 'graded')),

    CONSTRAINT fk_asub_student 
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_asub_assignment 
        FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE,
    CONSTRAINT fk_asub_enrollment 
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE
);

CREATE TABLE student_progress (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT NOT NULL,
    module_id       INT NOT NULL,
    enrollment_id   INT NOT NULL,
    progress_pct    DECIMAL(5,2) NOT NULL DEFAULT 0,
    last_accessed   TIMESTAMP,
    is_completed    BOOLEAN NOT NULL DEFAULT FALSE,
    weekly_engagement DECIMAL(6,2),
    risk_status     VARCHAR(20) NOT NULL DEFAULT 'normal'
        CHECK (risk_status IN ('critical', 'warning', 'normal')),

    CONSTRAINT fk_progress_student 
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_progress_module 
        FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE CASCADE,
    CONSTRAINT fk_progress_enrollment 
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE,
    CONSTRAINT uq_progress UNIQUE (student_id, module_id, enrollment_id)
);

-- Attendance & Risk
CREATE TABLE attendance_sessions (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id    INT NOT NULL,
    date        DATE NOT NULL,
    session_name VARCHAR(100),
    start_time  TIME,
    end_time    TIME,

    CONSTRAINT fk_session_batch 
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT uq_attendance_session UNIQUE (batch_id, date, session_name)
);

CREATE TABLE student_attendance (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  BIGINT NOT NULL,
    session_id  INT NOT NULL,
    enrollment_id INT NOT NULL,
    status      VARCHAR(20) NOT NULL 
        CHECK (status IN ('present', 'absent', 'late')),
    marked_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_att_student 
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_att_session 
        FOREIGN KEY (session_id) REFERENCES attendance_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_att_enrollment 
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE,
    CONSTRAINT uq_student_attendance UNIQUE (student_id, session_id)
);

CREATE TABLE student_risk_reports (
    id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id              BIGINT NOT NULL,
    batch_id                INT NOT NULL,
    avg_quiz_score          DECIMAL(5,2),
    attendance_percentage   DECIMAL(5,2),
    risk_status             VARCHAR(20) NOT NULL 
        CHECK (risk_status IN ('critical', 'warning', 'normal')),
    report_date             DATE NOT NULL DEFAULT CURRENT_DATE,
    notes                   TEXT,

    CONSTRAINT fk_risk_student 
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_risk_batch 
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE
);

CREATE TABLE batch_performance (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id            INT NOT NULL UNIQUE,
    overall_progress    DECIMAL(5,2),
    total_students      INT,
    current_module      VARCHAR(255),
    completion_rate     DECIMAL(5,2),
    updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_performance_batch 
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE
);