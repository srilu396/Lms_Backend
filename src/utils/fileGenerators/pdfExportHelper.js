const PDFDocument = require('pdfkit-table');

const PDF_COLORS = {
    primary: '#1E293B',       // Slate 800 - dark headers
    primaryLight: '#334155',  // Slate 700 - subtitles
    accent: '#4F46E5',        // Indigo 600 - accents & links
    lightBg: '#F8FAFC',       // Slate 50 - alternate table row & cards
    border: '#E2E8F0',        // Slate 200 - table & divider borders
    text: '#0F172A',          // Slate 900 - main text
    subtext: '#64748B',       // Slate 500 - metadata & footer
    white: '#FFFFFF',
    successBg: '#DCFCE7',
    successText: '#166534',
    dangerBg: '#FEE2E2',
    dangerText: '#991B1B',
    warningBg: '#FEF3C7',
    warningText: '#92400E',
    infoBg: '#E0E7FF',
    infoText: '#3730A3'
};

/**
 * Shared PDF Export Helper to ensure visual consistency and prevent pagination defects across all backend exports.
 */
class PDFExportHelper {
    get colors() {
        return PDF_COLORS;
    }

    /**
     * Create a standardized PDFDocument instance with safe defaults
     */
    createDocument(options = {}) {
        return new PDFDocument({
            margin: 30,
            size: 'A4',
            bufferPages: true,
            autoFirstPage: true,
            ...options
        });
    }

    /**
     * Draw standardized professional header banner on top of current page
     */
    drawHeader(doc, { title, organizationName = 'TRANSETU LMS', batchName, dateGenerated = new Date(), datePeriod }) {
        const pageWidth = doc.page.width;
        const margin = doc.page.margins.left;
        const contentWidth = pageWidth - (margin * 2);

        // Header Background Banner
        doc.rect(margin, 25, contentWidth, 55).fill(PDF_COLORS.primary);

        // Header Title (18pt Helvetica-Bold)
        doc.font('Helvetica-Bold')
           .fontSize(18)
           .fillColor(PDF_COLORS.white)
           .text(organizationName.toUpperCase(), margin + 15, 33, { width: contentWidth - 30 });

        // Subtitle (12pt Helvetica)
        doc.font('Helvetica')
           .fontSize(12)
           .fillColor('#94A3B8')
           .text(title, margin + 15, 56, { width: contentWidth - 30 });

        // Metadata line below banner (10pt Helvetica-Bold)
        let metaY = 90;
        doc.font('Helvetica-Bold')
           .fontSize(10)
           .fillColor(PDF_COLORS.text);

        const formattedDate = dateGenerated instanceof Date 
            ? dateGenerated.toLocaleString('en-US', { dateStyle: 'medium', timeStyle: 'short' })
            : String(dateGenerated);

        let metaLine = `Generated: ${formattedDate}`;
        if (batchName) {
            metaLine += `  |  Batch: ${batchName}`;
        }
        if (datePeriod) {
            metaLine += `  |  Period: ${datePeriod}`;
        }

        doc.text(metaLine, margin, metaY);
        metaY += 16;

        // Thin separator line
        doc.moveTo(margin, metaY)
           .lineTo(pageWidth - margin, metaY)
           .strokeColor(PDF_COLORS.border)
           .lineWidth(1)
           .stroke();

        doc.y = metaY + 15;
    }

    /**
     * Render a styled summary information card box
     */
    drawSummaryCard(doc, items = []) {
        if (!items || items.length === 0) return;

        const pageWidth = doc.page.width;
        const margin = doc.page.margins.left;
        const cardWidth = pageWidth - (margin * 2);
        const cardStartY = doc.y;
        const rowHeight = 20;
        const rowsCount = Math.ceil(items.length / 2);
        const cardHeight = 20 + (rowsCount * rowHeight);

        doc.rect(margin, cardStartY, cardWidth, cardHeight)
           .fillAndStroke(PDF_COLORS.lightBg, PDF_COLORS.border);

        items.forEach((item, index) => {
            const col = index % 2;
            const row = Math.floor(index / 2);
            const x = margin + 15 + (col * (cardWidth / 2));
            const y = cardStartY + 12 + (row * rowHeight);

            doc.font('Helvetica-Bold')
               .fontSize(10)
               .fillColor(PDF_COLORS.text)
               .text(`${item.label}: `, x, y, { continued: true })
               .font('Helvetica')
               .fontSize(10)
               .fillColor(PDF_COLORS.primaryLight)
               .text(String(item.value || 'N/A'));
        });

        doc.y = cardStartY + cardHeight + 15;
    }

    /**
     * Draw standardized footers across all buffered pages without causing page overflow
     */
    drawFooters(doc, footerText = 'Generated by LMS') {
        const pages = doc.bufferedPageRange();
        const pageWidth = doc.page.width;
        const pageHeight = doc.page.height;
        const margin = doc.page.margins.left;
        const footerY = pageHeight - 25;

        for (let i = 0; i < pages.count; i++) {
            doc.switchToPage(i);
            const origBottomMargin = doc.page.margins.bottom;
            doc.page.margins.bottom = 0; // Temporarily disable bottom margin page addition

            // Divider line
            doc.moveTo(margin, footerY - 5)
               .lineTo(pageWidth - margin, footerY - 5)
               .strokeColor(PDF_COLORS.border)
               .lineWidth(0.5)
               .stroke();

            // Footer Left Text (8pt Helvetica)
            doc.font('Helvetica')
               .fontSize(8)
               .fillColor(PDF_COLORS.subtext)
               .text(footerText, margin, footerY, { lineBreak: false });

            // Footer Right Page Numbering (8pt Helvetica)
            const pageStr = `Page ${i + 1} of ${pages.count}`;
            doc.text(pageStr, pageWidth - margin - 100, footerY, {
                width: 100,
                align: 'right',
                lineBreak: false
            });

            doc.page.margins.bottom = origBottomMargin;
        }
    }

    /**
     * Format status string
     */
    formatStatus(status) {
        if (!status) return 'N/A';
        return String(status).toUpperCase();
    }
}

module.exports = new PDFExportHelper();

