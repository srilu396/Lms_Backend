
CREATE TABLE users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            VARCHAR(100)  NOT NULL UNIQUE,
    email               VARCHAR(255)  NOT NULL UNIQUE,
    full_name           VARCHAR(255),
    role                VARCHAR(50)   NOT NULL
                            CHECK (role IN ('admin', 'tutor', 'student', 'institution_representative')),
    password_hash       VARCHAR(255)  NOT NULL,
    is_active           BOOLEAN       NOT NULL DEFAULT TRUE,
    student_code        VARCHAR(50),
    tutor_code          VARCHAR(50),
    email_verified_at   TIMESTAMP,
    last_login_at       TIMESTAMP,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at          TIMESTAMP
);

CREATE TABLE tutor_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id            BIGINT        NOT NULL UNIQUE,
    bio                 TEXT,
    profile_photo_url   VARCHAR(500),
    qualifications      TEXT,
    linkedin_url        VARCHAR(500),
    specialization      VARCHAR(255),
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_tutor_profile_user
        FOREIGN KEY (tutor_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL,
    token       VARCHAR(255)  NOT NULL UNIQUE,
    expires_at  TIMESTAMP     NOT NULL,
    is_used     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_reset_token_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE user_sessions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL,
    session_token    VARCHAR(255)  NOT NULL UNIQUE,
    expires_at       TIMESTAMP     NOT NULL,
    ip_address       VARCHAR(45),
    user_agent       TEXT,
    last_accessed_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_session_user
        FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);


-- =============================================================
-- SECTION 2: INSTITUTIONS
-- =============================================================

CREATE TABLE institutions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255)  NOT NULL,
    description TEXT,
    address     VARCHAR(500),
    phone       VARCHAR(50),
    email       VARCHAR(255),
    logo_url    VARCHAR(500),
    is_active   BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at  TIMESTAMP
);

CREATE TABLE institution_contacts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id  BIGINT        NOT NULL,
    name            VARCHAR(255)  NOT NULL,
    email           VARCHAR(255),
    phone           VARCHAR(50),
    is_primary      BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_contact_institution
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

CREATE TABLE tutor_institution_assignments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tutor_id        BIGINT    NOT NULL,
    institution_id  BIGINT    NOT NULL,
    is_active       BOOLEAN   NOT NULL DEFAULT TRUE,
    assigned_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    removed_at      TIMESTAMP,

    CONSTRAINT fk_tia_tutor
        FOREIGN KEY (tutor_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_tia_institution
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE,
    CONSTRAINT uq_tutor_institution
        UNIQUE (tutor_id, institution_id)
);


-- =============================================================
-- SECTION 3: COURSES & CONTENT HIERARCHY
-- =============================================================

CREATE TABLE courses (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255)  NOT NULL,
    description     TEXT,
    thumbnail_url   VARCHAR(500),
    institution_id  BIGINT        NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'inactive', 'archived')),
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at      TIMESTAMP,

    CONSTRAINT fk_course_institution
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

CREATE TABLE course_tutors (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   INT           NOT NULL,
    tutor_id    BIGINT        NOT NULL,
    role        VARCHAR(20)   NOT NULL DEFAULT 'primary'
                    CHECK (role IN ('primary', 'co_tutor')),
    assigned_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ct_course
        FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_ct_tutor
        FOREIGN KEY (tutor_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_course_tutor
        UNIQUE (course_id, tutor_id)
);

-- Enforce only ONE primary tutor per course
CREATE UNIQUE INDEX uq_primary_course_tutor
    ON course_tutors (course_id)
    WHERE role = 'primary';

CREATE TABLE modules (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   INT           NOT NULL,
    name        VARCHAR(255)  NOT NULL,
    order_num   INT           NOT NULL,
    is_locked   BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_module_course
        FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    CONSTRAINT uq_module_order
        UNIQUE (course_id, order_num)
);

CREATE TABLE topics (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id   INT           NOT NULL,
    name        VARCHAR(255)  NOT NULL,
    order_num   INT           NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_topic_module
        FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE CASCADE,
    CONSTRAINT uq_topic_order
        UNIQUE (module_id, order_num)
);

CREATE TABLE lessons (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id         INT           NOT NULL,
    name             VARCHAR(255)  NOT NULL,
    type             VARCHAR(20)   NOT NULL
                         CHECK (type IN ('video', 'text', 'image', 'mixed')),
    content_text     TEXT,
    image_url        VARCHAR(500),
    video_url        VARCHAR(500),
    duration_minutes INT,
    order_num        INT           NOT NULL,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_lesson_topic
        FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE CASCADE,
    CONSTRAINT uq_lesson_order
        UNIQUE (topic_id, order_num)
);


-- =============================================================
-- SECTION 4: BATCHES & ENROLLMENTS
-- =============================================================

CREATE TABLE batches (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100)  NOT NULL,
    start_date      DATE,
    end_date        DATE,
    allocation_time VARCHAR(100),
    course_id       INT           NOT NULL,
    institution_id  BIGINT        NOT NULL,
    status          VARCHAR(20)   NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'completed', 'cancelled')),
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at      TIMESTAMP,

    CONSTRAINT fk_batch_course
        FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_batch_institution
        FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE CASCADE
);

CREATE TABLE batch_tutors (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id    INT       NOT NULL,
    tutor_id    BIGINT    NOT NULL,
    is_primary  BOOLEAN   NOT NULL DEFAULT TRUE,
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_bt_batch
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT fk_bt_tutor
        FOREIGN KEY (tutor_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_batch_tutor
        UNIQUE (batch_id, tutor_id)
);

CREATE TABLE enrollments (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT      NOT NULL,
    batch_id        INT         NOT NULL,
    enrollment_date DATE        NOT NULL DEFAULT CURRENT_DATE,
    status          VARCHAR(20) NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'completed', 'dropped')),
    created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_enrollment_student
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollment_batch
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT uq_enrollment
        UNIQUE (student_id, batch_id)
);


-- =============================================================
-- SECTION 5: ANNOUNCEMENTS
-- =============================================================

CREATE TABLE announcements (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id    INT           NOT NULL,
    tutor_id    BIGINT        NOT NULL,
    title       VARCHAR(255)  NOT NULL,
    content     TEXT          NOT NULL,
    priority    VARCHAR(20)   NOT NULL DEFAULT 'normal'
                    CHECK (priority IN ('normal', 'important', 'urgent')),
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at  TIMESTAMP,

    CONSTRAINT fk_announcement_batch
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT fk_announcement_tutor
        FOREIGN KEY (tutor_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE announcement_reads (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    announcement_id INT       NOT NULL,
    student_id      BIGINT    NOT NULL,
    read_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_ar_announcement
        FOREIGN KEY (announcement_id) REFERENCES announcements(id) ON DELETE CASCADE,
    CONSTRAINT fk_ar_student
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT uq_announcement_read
        UNIQUE (announcement_id, student_id)
);


-- =============================================================
-- SECTION 6: NOTIFICATIONS
-- =============================================================

CREATE TABLE notifications (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id   BIGINT        NOT NULL,
    sender_user_id      BIGINT,
    title               VARCHAR(255)  NOT NULL,
    message             TEXT          NOT NULL,
    type                VARCHAR(50)   NOT NULL
                            CHECK (type IN (
                                'assignment_submitted',
                                'announcement_created',
                                'quiz_graded',
                                'assignment_graded',
                                'attendance_marked',
                                'risk_alert',
                                'system'
                            )),
    is_read             BOOLEAN       NOT NULL DEFAULT FALSE,
    reference_id        BIGINT,
    reference_type      VARCHAR(50),
    read_at             TIMESTAMP,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_notif_recipient
        FOREIGN KEY (recipient_user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_notif_sender
        FOREIGN KEY (sender_user_id) REFERENCES users(id) ON DELETE SET NULL
);


-- =============================================================
-- SECTION 7: QUIZZES
-- =============================================================

CREATE TABLE quizzes (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id            INT           NOT NULL,
    name                VARCHAR(255)  NOT NULL,
    instructions        TEXT,
    max_attempts        INT           NOT NULL DEFAULT 1,
    time_limit_minutes  INT,
    passing_score       INT,
    created_at          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_quiz_topic
        FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE CASCADE
);

CREATE TABLE quiz_questions (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id         INT           NOT NULL,
    question_text   TEXT          NOT NULL,
    options         JSONB,
    correct_answer  VARCHAR(500),
    type            VARCHAR(20)   NOT NULL
                        CHECK (type IN ('mcq', 'short')),
    marks           INT           NOT NULL DEFAULT 1,
    order_num       INT           NOT NULL,

    CONSTRAINT fk_question_quiz
        FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE,
    CONSTRAINT uq_question_order
        UNIQUE (quiz_id, order_num)
);

CREATE TABLE quiz_submissions (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT        NOT NULL,
    quiz_id         INT           NOT NULL,
    enrollment_id   INT           NOT NULL,
    attempt_number  INT           NOT NULL DEFAULT 1,
    score           DECIMAL(5,2),
    status          VARCHAR(30)   NOT NULL DEFAULT 'pending_review'
                        CHECK (status IN ('pending_review', 'reviewed', 'completed')),
    submitted_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_qs_student
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_qs_quiz
        FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE,
    CONSTRAINT fk_qs_enrollment
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE,
    CONSTRAINT uq_quiz_attempt
        UNIQUE (student_id, quiz_id, enrollment_id, attempt_number)
);

CREATE TABLE quiz_answers (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id   INT       NOT NULL,
    question_id     INT       NOT NULL,
    selected_answer TEXT,
    is_correct      BOOLEAN,
    answered_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_qa_submission
        FOREIGN KEY (submission_id) REFERENCES quiz_submissions(id) ON DELETE CASCADE,
    CONSTRAINT fk_qa_question
        FOREIGN KEY (question_id) REFERENCES quiz_questions(id) ON DELETE CASCADE
);


-- =============================================================
-- SECTION 8: ASSIGNMENTS
-- =============================================================

CREATE TABLE assignments (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id    INT           NOT NULL,
    name         VARCHAR(255)  NOT NULL,
    instructions TEXT,
    max_score    DECIMAL(5,2),
    status       VARCHAR(20)   NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active', 'completed', 'cancelled')),
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_assignment_module
        FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE CASCADE
);

CREATE TABLE assignment_criteria (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id   INT           NOT NULL,
    criteria_name   VARCHAR(255)  NOT NULL,
    max_points      DECIMAL(5,2)  NOT NULL,
    description     TEXT,

    CONSTRAINT fk_criteria_assignment
        FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE
);

CREATE TABLE batch_assignments (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id   INT         NOT NULL,
    batch_id        INT         NOT NULL,
    due_date        DATE,
    status          VARCHAR(20) NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active', 'completed', 'cancelled')),

    CONSTRAINT fk_ba_assignment
        FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE,
    CONSTRAINT fk_ba_batch
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT uq_batch_assignment
        UNIQUE (assignment_id, batch_id)
);

CREATE TABLE assignment_submissions (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      BIGINT        NOT NULL,
    assignment_id   INT           NOT NULL,
    enrollment_id   INT           NOT NULL,
    file_url        VARCHAR(500),
    grade           DECIMAL(5,2),
    feedback        TEXT,
    status          VARCHAR(30)   NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending', 'submitted', 'graded', 'resubmit_requested')),
    submitted_at    TIMESTAMP,
    graded_at       TIMESTAMP,
    created_at      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_as_student
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_as_assignment
        FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE,
    CONSTRAINT fk_as_enrollment
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE
);


-- =============================================================
-- SECTION 9: PROGRESS & ATTENDANCE
-- =============================================================

CREATE TABLE lesson_progress (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT        NOT NULL,
    lesson_id     INT           NOT NULL,
    enrollment_id INT           NOT NULL,
    is_completed  BOOLEAN       NOT NULL DEFAULT FALSE,
    video_watch_pct DECIMAL(5,2),
    completed_at  TIMESTAMP,
    last_accessed TIMESTAMP,

    CONSTRAINT fk_lp_student
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_lp_lesson
        FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE CASCADE,
    CONSTRAINT fk_lp_enrollment
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE,
    CONSTRAINT uq_lesson_progress
        UNIQUE (student_id, lesson_id, enrollment_id)
);

CREATE TABLE student_progress (
    id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id        BIGINT        NOT NULL,
    module_id         INT           NOT NULL,
    enrollment_id     INT           NOT NULL,
    progress_pct      DECIMAL(5,2)  NOT NULL DEFAULT 0.00,
    is_completed      BOOLEAN       NOT NULL DEFAULT FALSE,
    weekly_engagement DECIMAL(6,2),
    risk_status       VARCHAR(20)   NOT NULL DEFAULT 'normal'
                          CHECK (risk_status IN ('critical', 'warning', 'normal')),
    last_accessed     TIMESTAMP,
    updated_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sp_student
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_sp_module
        FOREIGN KEY (module_id) REFERENCES modules(id) ON DELETE CASCADE,
    CONSTRAINT fk_sp_enrollment
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE,
    CONSTRAINT uq_student_progress
        UNIQUE (student_id, module_id, enrollment_id)
);

CREATE TABLE attendance_sessions (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id     INT           NOT NULL,
    session_date DATE          NOT NULL,
    session_name VARCHAR(100),
    start_time   TIME,
    end_time     TIME,
    created_at   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_as_batch
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT uq_attendance_session
        UNIQUE (batch_id, session_date, session_name)
);

CREATE TABLE student_attendance (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT      NOT NULL,
    session_id    INT         NOT NULL,
    enrollment_id INT         NOT NULL,
    status        VARCHAR(20) NOT NULL
                      CHECK (status IN ('present', 'absent', 'late')),
    marked_at     TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_sa_student
        FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
    CONSTRAINT fk_sa_session
        FOREIGN KEY (session_id) REFERENCES attendance_sessions(id) ON DELETE CASCADE,
    CONSTRAINT fk_sa_enrollment
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE,
    CONSTRAINT uq_student_attendance
        UNIQUE (student_id, session_id)
);


-- =============================================================
-- SECTION 10: ANALYTICS & RISK
