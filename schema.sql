-- =============================================================
-- SECTION 11: PERFORMANCE INDEXES
-- =============================================================

-- Users
CREATE INDEX idx_users_role         ON users(role);
CREATE INDEX idx_users_email        ON users(email);
CREATE INDEX idx_users_fullname     ON users(full_name);
CREATE INDEX idx_users_deleted_at   ON users(deleted_at) WHERE deleted_at IS NULL;

-- Enrollments
CREATE INDEX idx_enrollments_student    ON enrollments(student_id);
CREATE INDEX idx_enrollments_batch      ON enrollments(batch_id);

-- Modules / Topics / Lessons
CREATE INDEX idx_modules_course     ON modules(course_id);
CREATE INDEX idx_topics_module      ON topics(module_id);
CREATE INDEX idx_lessons_topic      ON lessons(topic_id);

-- Quizzes
CREATE INDEX idx_quiz_submissions_student   ON quiz_submissions(student_id);
CREATE INDEX idx_quiz_submissions_quiz      ON quiz_submissions(quiz_id);
CREATE INDEX idx_quiz_answers_submission    ON quiz_answers(submission_id);

-- Assignments
CREATE INDEX idx_assignment_submissions_student     ON assignment_submissions(student_id);
CREATE INDEX idx_assignment_submissions_assignment  ON assignment_submissions(assignment_id);

-- Progress
CREATE INDEX idx_lesson_progress_student    ON lesson_progress(student_id);
CREATE INDEX idx_student_progress_student   ON student_progress(student_id);
CREATE INDEX idx_student_progress_module    ON student_progress(module_id);

-- Attendance
CREATE INDEX idx_attendance_sessions_batch  ON attendance_sessions(batch_id);
CREATE INDEX idx_student_attendance_student ON student_attendance(student_id);
CREATE INDEX idx_student_attendance_session ON student_attendance(session_id);

-- Notifications
CREATE INDEX idx_notifications_recipient    ON notifications(recipient_user_id);
CREATE INDEX idx_notifications_is_read      ON notifications(recipient_user_id, is_read);

-- Risk Reports
CREATE INDEX idx_risk_reports_student   ON student_risk_reports(student_id);
CREATE INDEX idx_risk_reports_batch     ON student_risk_reports(batch_id);

-- Announcements
CREATE INDEX idx_announcements_batch    ON announcements(batch_id);
CREATE INDEX idx_announcement_reads     ON announcement_reads(announcement_id);
