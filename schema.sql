    report_date           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_srr_student
        FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_srr_batch
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE,
    CONSTRAINT fk_srr_enrollment
        FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE
);

CREATE TABLE batch_performance (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id         INT           NOT NULL UNIQUE,
    overall_progress DECIMAL(5,2),
    total_students   INT,
    current_module   VARCHAR(255),
    completion_rate  DECIMAL(5,2),
    updated_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_bp_batch
        FOREIGN KEY (batch_id) REFERENCES batches(id) ON DELETE CASCADE
